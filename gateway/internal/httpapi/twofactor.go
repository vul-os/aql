// GET /v1/auth/2fa — status for the caller. Served by store.TOTPStatus, whose
// SQL does not select the secret column, so this response shape cannot carry
// it even by accident.
func (s *Server) handleTwoFactorStatus(w http.ResponseWriter, r *http.Request) {
	c := claimsFrom(r)
	st, err := s.store.TOTPStatus(r.Context(), c.Sub)
	if err != nil {
		s.log.Error("totp status", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"enrolled":     st.Enrolled,
		"active":       st.Active,
		"pending":      st.Pending,
		"created_at":   st.CreatedAt,
		"activated_at": nullInt64(st.ActivatedAt),
		// Surfaced so a user cannot silently reach zero — see the sole-admin
		// lockout note in this file's doc comment.
		"recovery_codes_remaining": st.RecoveryCodesRemaining,
		"algorithm":                totpAlgorithm,
		"digits":                   totpDigits,
		"period_seconds":           totpPeriodS,
	})
}

// POST /v1/auth/2fa/enroll — begin enrolment.
//
// Returns the secret and the otpauth:// URI ONCE. Nothing gates login yet:
// the factor is pending until POST /v1/auth/2fa/activate proves possession.
//
// Throttled on the register (issuance) budget rather than the login one, the
// same call authrecovery.go's forgot-password makes: this endpoint writes a
// row, it does not check a credential.
func (s *Server) handleTwoFactorEnroll(w http.ResponseWriter, r *http.Request) {
	if !s.authIPGate(w, r, "totp_enroll_ip", s.cfg.AuthRateLimits.RegisterIPPerWindow) {
		return
	}
	c := claimsFrom(r)
	u, err := s.store.UserByID(r.Context(), c.Sub)
	if err != nil {
		writeErr(w, http.StatusUnauthorized, "unauthorized")
		return
	}
	secret, err := newTOTPSecret()
	if err != nil {
		s.log.Error("totp secret generation failed", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	f, err := s.store.CreateTOTPEnrollment(r.Context(), u.ID, secret, totpDigits, totpPeriodS)
	if errors.Is(err, store.ErrTOTPAlreadyActive) {
		// Deliberate: re-enrolling over a live factor would be a way for a
		// stolen session to swap the second factor without proving anything.
		writeErr(w, http.StatusConflict, "totp_already_active")
		return
	}
	if err != nil {
		s.log.Error("totp enroll", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	// Audited — but the detail names only the factor, never the secret.
	if err := s.store.WriteAdminAudit(r.Context(), u.ID, "2fa_enroll_start", "user", u.ID, true,
		map[string]any{"factor_id": f.ID}); err != nil {
		s.log.Error("audit 2fa_enroll_start", "err", err)
	}
	// The ONE moment the secret is visible. There is no second one.
	writeJSON(w, http.StatusCreated, map[string]any{
		"secret":            secret,
		"otpauth_uri":       otpauthURI(totpIssuer, u.Username, secret, totpDigits, totpPeriodS),
		"algorithm":         totpAlgorithm,
		"digits":            totpDigits,
		"period_seconds":    totpPeriodS,
		"secret_shown_once": true,
		"pending":           true,
	})
}

// DELETE /v1/auth/2fa/enroll — abandon an unproven enrolment.
//
// Refuses to touch an ACTIVE factor: turning real 2FA off is the disable
// route's job and requires proving possession. This exists only so "I closed
// the tab halfway through" is not a state a user must prove their way out of.
func (s *Server) handleTwoFactorEnrollCancel(w http.ResponseWriter, r *http.Request) {
	c := claimsFrom(r)
	f, err := s.store.LiveTOTPFactor(r.Context(), c.Sub)
	if errors.Is(err, store.ErrNotFound) {
		writeErr(w, http.StatusNotFound, "no_pending_enrollment")
		return
	}
	if err != nil {
		s.log.Error("live totp lookup", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if err := s.store.CancelPendingTOTP(r.Context(), f.ID, c.Sub); err != nil {
		// ErrTOTPUnusable here means the factor is active — the honest answer
		// is "there is no pending enrolment to cancel", not a 500.
		writeErr(w, http.StatusNotFound, "no_pending_enrollment")
		return
	}
	if err := s.store.WriteAdminAudit(r.Context(), c.Sub, "2fa_enroll_cancel", "user", c.Sub, true,
		map[string]any{"factor_id": f.ID}); err != nil {
		s.log.Error("audit 2fa_enroll_cancel", "err", err)
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true})
}

type twoFactorActivateReq struct {
	TOTPCode string `json:"totp_code"`
}

// POST /v1/auth/2fa/activate — prove possession and turn 2FA on.
//
// The proving code, the activation and the recovery-code batch all land in
// ONE transaction (store.ActivateTOTP): 2FA is never on without an escape
// hatch, and the proving code's counter is spent so it cannot be immediately
// replayed as a login.
//
// The recovery codes are in the response body. That is the only time they
// exist outside a salted digest.
func (s *Server) handleTwoFactorActivate(w http.ResponseWriter, r *http.Request) {
	if !s.authIPGate(w, r, "totp_activate_ip", s.cfg.AuthRateLimits.LoginIPPerWindow) {
		return
	}
	c := claimsFrom(r)
	var req twoFactorActivateReq
	if !readJSON(w, r, &req) {
		return
	}
	f, err := s.store.LiveTOTPFactor(r.Context(), c.Sub)
	if errors.Is(err, store.ErrNotFound) {
		writeErr(w, http.StatusConflict, "no_pending_enrollment")
		return
	}
	if err != nil {
		s.log.Error("live totp lookup", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if !f.Pending() {
		writeErr(w, http.StatusConflict, "no_pending_enrollment")
		return
	}
	if !s.totpVerifyGate(w, r, c.Sub) {
		return
	}
	// Activation accepts an authenticator code only. A recovery code cannot
	// activate a factor: none exist yet, and accepting the field here would
	// invite a caller to believe otherwise.
	claim, ok := s.verifySecondFactor(r.Context(), f, twoFactorInput{TOTPCode: req.TOTPCode})
	if !ok || claim.Kind != store.SecondFactorTOTP {
		s.recordTOTPFailure(r.Context(), c.Sub)
		writeErr(w, http.StatusUnauthorized, "invalid_second_factor")
		return
	}
	plain, seeds, err := newRecoveryCodes()
	if err != nil {
		s.log.Error("recovery code generation failed", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if err := s.store.ActivateTOTP(r.Context(), f.ID, c.Sub, claim.Step, seeds); err != nil {
		if errors.Is(err, store.ErrTOTPUnusable) {
			writeErr(w, http.StatusConflict, "no_pending_enrollment")
			return
		}
		s.log.Error("totp activate", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if err := s.store.WriteAdminAudit(r.Context(), c.Sub, "2fa_activate", "user", c.Sub, true,
		map[string]any{"factor_id": f.ID, "recovery_codes": len(plain)}); err != nil {
		s.log.Error("audit 2fa_activate", "err", err)
	}
	writeJSON(w, http.StatusOK, map[string]any{
		"active":                    true,
		"recovery_codes":            plain,
		"recovery_codes_shown_once": true,
	})
}

// POST /v1/auth/2fa/disable — turn 2FA off, and prove possession to do it.
//
// A current authenticator code or an unspent recovery code is REQUIRED. A
// live session is not enough, and that is the entire point: the second factor
// exists to survive a stolen session, so a stolen session must not be able to
// remove it. Whichever credential is presented is SPENT in the same
// transaction as the teardown, so it cannot be replayed afterwards.
func (s *Server) handleTwoFactorDisable(w http.ResponseWriter, r *http.Request) {
	if !s.authIPGate(w, r, "totp_disable_ip", s.cfg.AuthRateLimits.LoginIPPerWindow) {
		return
	}
	c := claimsFrom(r)
	var in twoFactorInput
	if !readJSON(w, r, &in) {
		return
	}
	if in.both() {
		writeErr(w, http.StatusBadRequest, "conflicting_second_factor")
		return
	}
	if in.empty() {
		// The refusal this route exists for. Never a 200.
		writeErr(w, http.StatusBadRequest, "second_factor_required")
		return
	}
	f, err := s.store.LiveTOTPFactor(r.Context(), c.Sub)
	if errors.Is(err, store.ErrNotFound) {
		writeErr(w, http.StatusConflict, "totp_not_active")
		return
	}
	if err != nil {
		s.log.Error("live totp lookup", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if !f.Active() {
		writeErr(w, http.StatusConflict, "totp_not_active")
		return
	}
	if !s.totpVerifyGate(w, r, c.Sub) {
		return
	}
	claim, ok := s.verifySecondFactor(r.Context(), f, in)
	if !ok {
		s.recordTOTPFailure(r.Context(), c.Sub)
		if err := s.store.WriteAdminAudit(r.Context(), c.Sub, "2fa_disable", "user", c.Sub, false,
			map[string]any{"reason": "invalid_second_factor"}); err != nil {
			s.log.Error("audit 2fa_disable", "err", err)
		}
		writeErr(w, http.StatusUnauthorized, "invalid_second_factor")
		return
	}
	if err := s.store.DisableTOTP(r.Context(), c.Sub, claim); err != nil {
		if errors.Is(err, store.ErrTOTPUnusable) {
			s.recordTOTPFailure(r.Context(), c.Sub)
			writeErr(w, http.StatusUnauthorized, "invalid_second_factor")
			return
		}
		s.log.Error("totp disable", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return
	}
	if err := s.store.WriteAdminAudit(r.Context(), c.Sub, "2fa_disable", "user", c.Sub, true,
		map[string]any{"factor_id": f.ID, "method": string(claim.Kind)}); err != nil {
		s.log.Error("audit 2fa_disable", "err", err)
	}
	writeJSON(w, http.StatusOK, map[string]any{"ok": true, "active": false})
}
