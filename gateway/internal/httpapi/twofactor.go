// twoFactorInput is the second-factor half of a request body. Exactly one of
// the two may be set; sending both is a structural error rather than a
// silently-preferred field, so a caller can never believe they proved
// something they did not.
type twoFactorInput struct {
	TOTPCode     string `json:"totp_code"`
	RecoveryCode string `json:"recovery_code"`
}

func (in twoFactorInput) empty() bool {
	return strings.TrimSpace(in.TOTPCode) == "" && strings.TrimSpace(in.RecoveryCode) == ""
}

func (in twoFactorInput) both() bool {
	return strings.TrimSpace(in.TOTPCode) != "" && strings.TrimSpace(in.RecoveryCode) != ""
}

// totpVerifyGate is the shared throttle in front of every code check. It
// writes the response itself on denial/error and returns false — the same
// shape as authIPGate.
//
// Fails CLOSED on a counter-store error, for the reason
// store/authratelimit.go gives: a brute-force gate that silently disables
// itself on a SQLite hiccup is worse than a briefly unavailable endpoint.
func (s *Server) totpVerifyGate(w http.ResponseWriter, r *http.Request, userID string) bool {
	over, retry, err := s.store.AuthAttemptsOverCap(r.Context(), totpVerifyScope, "user:"+userID,
		totpVerifyPerWindow, time.Now().Unix())
	if err != nil {
		s.log.Error("2fa rate limit check failed", "err", err)
		writeErr(w, http.StatusServiceUnavailable, "rate_limit_unavailable")
		return false
	}
	if over {
		w.Header().Set("Retry-After", strconv.FormatInt(retry, 10))
		writeErr(w, http.StatusTooManyRequests, "rate_limited")
		return false
	}
	return true
}

// recordTOTPFailure spends one unit of the shared budget. Called ONLY after a
// verification actually failed — never on a merely absent code, which is the
// normal first leg of a two-step login and must not cost a user their budget.
func (s *Server) recordTOTPFailure(ctx context.Context, userID string) {
	if err := s.store.RecordAuthFailure(ctx, totpVerifyScope, "user:"+userID, time.Now().Unix()); err != nil {
		s.log.Error("record 2fa failure", "err", err)
	}
}

// verifySecondFactor turns a presented credential into an unspent claim, or
// reports one indistinguishable failure. It does not spend anything — see
// store.SecondFactorClaim.
//
// The factor's OWN digits/period are used, not the current package defaults,
// so an enrolment provisioned under different parameters keeps working.
func (s *Server) verifySecondFactor(ctx context.Context, f *store.TOTPFactor, in twoFactorInput) (store.SecondFactorClaim, bool) {
	if strings.TrimSpace(in.RecoveryCode) != "" {
		rows, err := s.store.LiveRecoveryCodes(ctx, f.ID)
		if err != nil {
			s.log.Error("load recovery codes", "err", err)
			return store.SecondFactorClaim{}, false
		}
		id, ok := matchRecoveryCode(rows, normalizeRecoveryCode(in.RecoveryCode))
		if !ok {
			return store.SecondFactorClaim{}, false
		}
		return store.SecondFactorClaim{
			Kind: store.SecondFactorRecoveryCode, FactorID: f.ID, CodeID: id,
		}, true
	}

	code, wellFormed := normalizeTOTPCode(in.TOTPCode, f.Digits)
	if !wellFormed {
		return store.SecondFactorClaim{}, false
	}
	secret, err := b32.DecodeString(f.Secret)
	if err != nil {
		// A secret that will not decode is a corrupt row, not a user error.
		// Fail closed and say nothing about it to the caller.
		s.log.Error("totp secret decode failed", "factor_id", f.ID)
		return store.SecondFactorClaim{}, false
	}
	step, ok := verifyTOTP(secret, f.Digits, f.PeriodS, totpSkewSteps, code, time.Now().Unix())
	if !ok {
		return store.SecondFactorClaim{}, false
	}
	// Early replay check: a code from a step already spent is refused here so
	// the caller gets the ordinary "wrong code" answer. This is an early-out
	// only — the authority is the guarded UPDATE in the store, which is what
	// actually wins the concurrent-replay race.
	if f.LastStep.Valid && step <= f.LastStep.Int64 {
		return store.SecondFactorClaim{}, false
	}
	return store.SecondFactorClaim{Kind: store.SecondFactorTOTP, FactorID: f.ID, Step: step}, true
}

// ---------------------------------------------------------------------------
// The login gate (called from auth.go's handleLogin)
// ---------------------------------------------------------------------------

// secondFactorGate runs after the password has verified and decides whether a
// session may be issued. It returns (nil, true) — no claim, proceed — for the
// overwhelmingly common case of a user with no ACTIVE factor, which is what
// keeps login byte-for-byte unchanged for everyone who has not enrolled.
//
// It writes the response itself on refusal and returns false.
//
// FAILS CLOSED. If the factor lookup errors, we cannot tell whether 2FA is on,
// so no session is issued. A read error must never degrade into
// password-only login.
func (s *Server) secondFactorGate(w http.ResponseWriter, r *http.Request, u *store.User, in twoFactorInput) (*store.SecondFactorClaim, bool) {
	f, err := s.store.LiveTOTPFactor(r.Context(), u.ID)
	if errors.Is(err, store.ErrNotFound) {
		return nil, true
	}
	if err != nil {
		s.log.Error("live totp lookup", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return nil, false
	}
	if !f.Active() {
		// Pending enrolment: gates nothing. See "ENROL → PROVE → ACTIVATE".
		return nil, true
	}
	if in.both() {
		writeErr(w, http.StatusBadRequest, "conflicting_second_factor")
		return nil, false
	}
	if in.empty() {
		// Not a failure — the client now knows to ask for a code and retry
		// with the password. Deliberately does NOT spend rate-limit budget.
		//
		// There is no intermediate "half-authenticated" token here on
		// purpose: the password is presented again with the code, so there is
		// no short-lived credential to steal, replay, or forget to expire.
		writeErr(w, http.StatusUnauthorized, "totp_required")
		return nil, false
	}
	if !s.totpVerifyGate(w, r, u.ID) {
		return nil, false
	}
	claim, ok := s.verifySecondFactor(r.Context(), f, in)
	if !ok {
		s.recordTOTPFailure(r.Context(), u.ID)
		if err := s.store.WriteAdminAudit(r.Context(), u.ID, "2fa_login", "user", u.ID, false,
			map[string]any{"reason": "invalid_second_factor"}); err != nil {
			s.log.Error("audit 2fa_login", "err", err)
		}
		// One refusal for every cause — wrong code, replayed code, expired
		// step, unknown recovery code, already-spent recovery code.
		writeErr(w, http.StatusUnauthorized, "invalid_second_factor")
		return nil, false
	}
	return &claim, true
}

// issueTokensClaimed issues access+refresh, spending a second-factor claim in
// the SAME transaction as the refresh-token insert when one is present.
//
// A nil claim is the no-2FA path and behaves exactly like the original
// issueTokensCtx: one unconditional insert. This is the single funnel both
// paths go through, so there is no way to add a login route that quietly skips
// the claim.
func (s *Server) issueTokensClaimed(w http.ResponseWriter, r *http.Request, u *store.User, claim *store.SecondFactorClaim) (map[string]any, bool) {
	access, err := SignJWT(s.cfg.JWTSecret, u.ID, u.Username, u.IsPlatformAdmin, accessTTL)
	if err != nil {
		writeErr(w, http.StatusInternalServerError, "internal")
		return nil, false
	}
	refresh := randomToken()
	expiresAt := time.Now().Add(refreshTTL).Unix()

	if claim == nil {
		if err := s.store.InsertRefreshToken(r.Context(), store.NewID(), store.NewID(), u.ID,
			hashToken(refresh), expiresAt); err != nil {
			writeErr(w, http.StatusInternalServerError, "internal")
			return nil, false
		}
		return map[string]any{"access_token": access, "refresh_token": refresh}, true
	}

	err = s.store.ClaimSecondFactorAndIssueRefresh(r.Context(), u.ID, *claim,
		store.NewID(), store.NewID(), hashToken(refresh), expiresAt)
	if errors.Is(err, store.ErrTOTPUnusable) {
		// Lost the replay/double-spend race between verification and claim.
		// Same refusal a wrong code gets, and no session exists.
		s.recordTOTPFailure(r.Context(), u.ID)
		writeErr(w, http.StatusUnauthorized, "invalid_second_factor")
		return nil, false
	}
	if err != nil {
		s.log.Error("claim second factor", "err", err)
		writeErr(w, http.StatusInternalServerError, "internal")
		return nil, false
	}
	if err := s.store.WriteAdminAudit(r.Context(), u.ID, "2fa_login", "user", u.ID, true,
		map[string]any{"method": string(claim.Kind)}); err != nil {
		s.log.Error("audit 2fa_login", "err", err)
	}
	return map[string]any{"access_token": access, "refresh_token": refresh}, true
}

