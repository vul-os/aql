const (
	// See "PARAMETERS" in this file's doc comment for each of these.
	totpDigits    = 6
	totpPeriodS   = 30
	totpSkewSteps = 1
	// totpSecretBytes is 160 bits — RFC 4226 §4 R6's recommendation for an
	// HMAC-SHA1 key, and what every authenticator app expects.
	totpSecretBytes = 20
	// totpAlgorithm is what goes in the otpauth:// URI. Changing it here
	// without changing hotpCode below would provision apps with a secret this
	// server cannot verify.
	totpAlgorithm = "SHA1"
	// totpIssuer labels the entry in the user's authenticator app.
	totpIssuer = "Aql"

	// totpVerifyPerWindow is the shared failure budget for EVERY code
	// verification in this file, per user, per store.AuthWindowS. A constant,
	// not configuration — see this file's doc comment.
	totpVerifyPerWindow = 5
	// totpVerifyScope is the single rate-limit counter scope all three
	// verifying endpoints share, so switching endpoints does not buy a fresh
	// budget.
	totpVerifyScope = "totp_verify_acct"

	// Recovery codes: ten of them, 16 characters each from a 32-symbol
	// alphabet (80 bits), grouped in fours for transcription.
	recoveryCodeCount     = 10
	recoveryCodeChars     = 16
	recoveryCodeGroup     = 4
	totpRecoverySaltBytes = 16 // 128 bits, per row

	// recoveryCodeAlphabet is RFC 4648 base32's alphabet: 32 symbols, so a
	// random byte maps to one with no modulo bias, and no lowercase/digit
	// confusion (no 0/O, no 1/I/l) when a human copies one off paper.
	recoveryCodeAlphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567"

	// totpRecoveryHashDomain separates these digests from every other SHA-256
	// in this codebase (recovery-token verifiers, API-token verifiers, the
	// audit chain), so no digest computed for one purpose can be replayed as a
	// valid value for another.
	totpRecoveryHashDomain = "aql/totp-recovery/v1/"
)

// b32 is the encoding for both the shared secret and the recovery-code
// alphabet: RFC 4648 base32, unpadded (authenticator apps reject '=').
var b32 = base32.StdEncoding.WithPadding(base32.NoPadding)

// ---------------------------------------------------------------------------
// RFC 4226 / RFC 6238
// ---------------------------------------------------------------------------

// hotpCode is RFC 4226 §5.3: HMAC-SHA1 over the 8-byte big-endian counter,
// dynamically truncated to a 31-bit integer, reduced mod 10^digits.
//
// This is the whole of the algorithm, in fourteen lines, using only the
// standard library. There is no dependency here and there does not need to be.
func hotpCode(secret []byte, counter uint64, digits int) string {
	var msg [8]byte
	binary.BigEndian.PutUint64(msg[:], counter)
	mac := hmac.New(sha1.New, secret)
	mac.Write(msg[:])
	sum := mac.Sum(nil)

	// Dynamic truncation: the low nibble of the last byte selects the offset.
	off := sum[len(sum)-1] & 0x0f
	// The high bit is masked off so the result is sign-agnostic across
	// implementations — RFC 4226 is explicit about this.
	bin := uint32(sum[off]&0x7f)<<24 |
		uint32(sum[off+1])<<16 |
		uint32(sum[off+2])<<8 |
		uint32(sum[off+3])

	mod := uint32(1)
	for i := 0; i < digits; i++ {
		mod *= 10
	}
	return fmt.Sprintf("%0*d", digits, bin%mod)
}

// totpCounter is RFC 6238's T = floor(unixTime / period). The Unix epoch is
// T0 = 0, the default.
func totpCounter(nowUnix int64, periodS int) int64 {
	return nowUnix / int64(periodS)
}

// verifyTOTP checks a presented code against every counter within skew of
// now, and reports which step matched.
//
// CONSTANT WORK ACROSS CANDIDATES: it never returns early on a match. Every
// candidate step is computed and compared on every call, and the match is
// accumulated, so the time taken does not reveal WHICH step matched (or that
// any did). The comparison itself is subtle.ConstantTimeCompare.
//
// The caller is still responsible for replay: this function reports the step,
// and only store.claimSecondFactorTx's guarded UPDATE decides whether that
// step may be spent. Check-then-act here would lose the race.
func verifyTOTP(secret []byte, digits, periodS, skew int, code string, nowUnix int64) (step int64, ok bool) {
	base := totpCounter(nowUnix, periodS)
	matched := 0
	var matchedStep int64
	for d := -skew; d <= skew; d++ {
		s := base + int64(d)
		if s < 0 {
			continue
		}
		want := hotpCode(secret, uint64(s), digits)
		eq := subtle.ConstantTimeCompare([]byte(want), []byte(code))
		// Branch-free accumulate: record the step on a match without a
		// conditional that would let the loop exit early.
		matchedStep = int64(subtle.ConstantTimeSelect(eq, int(s), int(matchedStep)))
		matched |= eq
	}
	return matchedStep, matched == 1
}

// normalizeTOTPCode accepts what a human actually types — "123 456", with
// stray whitespace — and rejects anything that is not exactly `digits` ASCII
// digits.
//
// This structural rejection happens BEFORE any HMAC is computed and is not a
// timing oracle: the length and character set of a valid code are public
// facts about RFC 6238, not facts about this user's secret.
func normalizeTOTPCode(raw string, digits int) (string, bool) {
	var b strings.Builder
	for _, r := range raw {
		switch {
		case r == ' ' || r == '-' || r == '\t':
			continue
		case r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			return "", false
		}
	}
	s := b.String()
	if len(s) != digits {
		return "", false
	}
	return s, true
}

// newTOTPSecret returns a fresh base32 secret. An error from crypto/rand is
// fatal to the request — fail closed, never fall back to a weaker source.
func newTOTPSecret() (string, error) {
	b := make([]byte, totpSecretBytes)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	return b32.EncodeToString(b), nil
}

// otpauthURI builds the standard provisioning URI a client renders as a QR
// code (the de-facto Key Uri Format). All parameters are stated explicitly
// rather than left to an app's defaults, so an app that defaults differently
// still provisions something this server can verify.
//
// The secret is IN this string. It is returned to the enrolling user once and
// must be treated exactly like the secret itself — never logged, never stored.
func otpauthURI(issuer, username, secretB32 string, digits, periodS int) string {
	q := url.Values{}
	q.Set("secret", secretB32)
	q.Set("issuer", issuer)
	q.Set("algorithm", totpAlgorithm)
	q.Set("digits", strconv.Itoa(digits))
	q.Set("period", strconv.Itoa(periodS))
	u := url.URL{
		Scheme:   "otpauth",
		Host:     "totp",
		Path:     "/" + issuer + ":" + username,
		RawQuery: q.Encode(),
	}
	return u.String()
}

// ---------------------------------------------------------------------------
// Recovery codes
// ---------------------------------------------------------------------------

// totpRecoveryHash is the one derivation both issuance and verification use.
func totpRecoveryHash(salt, code string) string {
	h := sha256.New()
	h.Write([]byte(totpRecoveryHashDomain))
	h.Write([]byte(salt))
	h.Write([]byte{0})
	h.Write([]byte(code))
	return hex.EncodeToString(h.Sum(nil))
}

// normalizeRecoveryCode makes transcription forgiving without making matching
// loose: case is folded up, and the grouping separators a human might or might
// not type are dropped. Everything else is preserved, so a wrong character is
// still a wrong code.
func normalizeRecoveryCode(raw string) string {
	var b strings.Builder
	for _, r := range strings.ToUpper(strings.TrimSpace(raw)) {
		if r == '-' || r == ' ' || r == '\t' {
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}

// newRecoveryCodes mints a batch: the plaintexts to show exactly once, and
// the salted digests to store. The two slices are parallel only in the sense
// that they were generated together — nothing links a stored row back to its
// plaintext, by construction.
func newRecoveryCodes() (plain []string, seeds []store.RecoveryCodeSeed, err error) {
	for i := 0; i < recoveryCodeCount; i++ {
		raw := make([]byte, recoveryCodeChars)
		if _, err := rand.Read(raw); err != nil {
			return nil, nil, err
		}
		var b strings.Builder
		for j, x := range raw {
			if j > 0 && j%recoveryCodeGroup == 0 {
				b.WriteByte('-')
			}
			// len(alphabet) is exactly 32, so &31 is an unbiased map from a
			// uniform byte. Do not change the alphabet length without
			// replacing this with rejection sampling.
			b.WriteByte(recoveryCodeAlphabet[x&31])
		}
		display := b.String()

		saltRaw := make([]byte, totpRecoverySaltBytes)
		if _, err := rand.Read(saltRaw); err != nil {
			return nil, nil, err
		}
		salt := hex.EncodeToString(saltRaw)
		plain = append(plain, display)
		seeds = append(seeds, store.RecoveryCodeSeed{
			Salt:     salt,
			CodeHash: totpRecoveryHash(salt, normalizeRecoveryCode(display)),
		})
	}
	return plain, seeds, nil
}

// dummyRecoveryCodeSalt keeps the "no codes left" and "wrong code" paths
// costing the same: matchRecoveryCode always performs at least one digest and
// one constant-time compare. Same technique handleLogin uses with dummyHash.
var dummyRecoveryCodeSalt = hex.EncodeToString(make([]byte, totpRecoverySaltBytes))

// matchRecoveryCode tests a presented code against every unspent row and
// returns the id of the one that matched.
//
// Like verifyTOTP, it does NOT return early: every row is hashed and compared
// on every call, so the time taken does not leak the position of the matching
// code (or the number of codes remaining). A match here is not authorisation —
// store.claimSecondFactorTx's guarded UPDATE is.
func matchRecoveryCode(rows []store.RecoveryCodeRow, presented string) (string, bool) {
	// Burn one comparison even with nothing to compare against.
	if len(rows) == 0 {
		_ = subtle.ConstantTimeCompare(
			[]byte(totpRecoveryHash(dummyRecoveryCodeSalt, presented)),
			[]byte(totpRecoveryHash(dummyRecoveryCodeSalt, "never-a-real-code")))
		return "", false
	}
	matched := 0
	matchedID := ""
	for _, row := range rows {
		got := totpRecoveryHash(row.Salt, presented)
		if subtle.ConstantTimeCompare([]byte(got), []byte(row.CodeHash)) == 1 {
			matched = 1
			matchedID = row.ID
		}
	}
	return matchedID, matched == 1
}

