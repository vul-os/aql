package httpapi

// Two-factor authentication (TOTP, RFC 6238) for console login, and the
// single-use recovery codes that are its escape hatch. The persistence half
// — liveness, the atomic claims, the replay guard — is store/twofactor.go;
// the schema rationale is migrations/0016_two_factor.sql. This file owns the
// two things neither of those can: THE ALGORITHM, and the decision about what
// a presented code is worth.
//
// WHY THIS EXISTS. This console opens physical gates. A password is a single
// string that can be phished, reused from a breach, or read off a sticky
// note, and today it is the only thing between an attacker and a gate motor.
// A second factor makes a stolen password insufficient on its own.
//
// ============================================================================
// THE SECRET IS RECOVERABLE, AND CANNOT BE OTHERWISE
// ============================================================================
// Verifying a TOTP means the server recomputing HMAC-SHA1(secret, counter) and
// comparing. That requires the secret in plaintext. There is no hashing scheme
// that changes this; it is a property of the algorithm, not a shortcut.
//
// So the TOTP secret is the same class of value as the webhook signing key
// (webhooks.go) and the OPPOSITE class from a password (password.go) or a
// recovery-token verifier (authrecovery.go). It gets the signing key's
// discipline:
//
//	* generated by crypto/rand, 20 bytes / 160 bits (RFC 4226 §4 R6);
//	* handed to a client exactly ONCE, in the 201 body of
//	  POST /v1/auth/2fa/enroll, as the base32 string plus the otpauth:// URI
//	  a client renders as a QR code. There is no "show it again" endpoint and
//	  there cannot be one — losing it means disabling and re-enrolling;
//	* never in a listing projection: GET /v1/auth/2fa is served by
//	  store.TOTPStatus, whose SQL does not select the column at all;
//	* never logged, never in an error string, never in an audit detail.
//
// If you add a debug print of a secret here, you have written a
// gate-opening primitive that regenerates itself every thirty seconds.
//
// Stated plainly, because it bounds what this feature claims: anyone who can
// read the database file can mint valid codes for every enrolled user. 2FA
// here defends against a stolen PASSWORD, not against a stolen database.
//
// The RECOVERY CODES get the opposite treatment, because they are presented
// verbatim and compared — so they are hashed at rest, salted per row, and
// single-use. See "recovery codes" below.
//
// ============================================================================
// PARAMETERS, AND WHY EACH ONE
// ============================================================================
//	algorithm  HMAC-SHA1. RFC 6238's default and the only one Google
//	           Authenticator, Aegis, 1Password, Bitwarden and every other
//	           mainstream app accept without fuss. SHA-1's collision weakness
//	           is irrelevant to HMAC, which depends on PRF security; HMAC-SHA1
//	           remains unbroken (RFC 6194). Interoperability wins here, and it
//	           costs nothing real.
//	digits     6. The universal default. Eight would add ~6.6 bits, which is
//	           worth far less than the rate limit below is, at the price of an
//	           enrolment that half the apps display wrong.
//	period     30 seconds. RFC 6238's default X.
//	skew       ±1 step. See the next section — it is the one parameter here
//	           where "a bit more generous" is a real weakening.
//
// ============================================================================
// CLOCK SKEW: ±1 STEP, AND THE ARITHMETIC THAT PICKS IT
// ============================================================================
// A code is accepted from the current step, the one before, and the one
// after: THREE valid codes at any instant, a ~90 second acceptance window.
//
// RFC 6238 §5.2 names exactly this: validators SHOULD accept at most one time
// step of skew, and anything wider is a stated security tradeoff. One step
// absorbs the two real-world sources of drift — an NTP-synced phone against a
// self-hosted box whose own clock may be seconds off, and a human who reads a
// code at 29.5 seconds and finishes typing it at 31 — without paying for
// anything else.
//
// What "wider" would cost, concretely. Guessing a 6-digit code is 1 in 10^6
// per try; with a 3-code window it is 3 in 10^6. Each extra step either side
// adds two more valid codes, so ±2 is 5 in 10^6 — a 67% increase in an
// attacker's per-attempt odds, bought for drift that a correctly-configured
// clock does not have. It is not free, so it is not taken.
//
// FORWARD skew is symmetric with backward on purpose: the drift here is as
// likely to be the SERVER's (a self-hosted box that has been up for months
// without NTP) as the phone's. A future-step code, once spent, sets last_step
// forward — so the user's next code is refused until the clock catches up.
// That is a deliberate, visible thirty seconds of friction, not a hole.
//
// ============================================================================
// RATE LIMITING: THE THING THAT ACTUALLY MAKES SIX DIGITS ENOUGH
// ============================================================================
// A million possibilities is nothing against an unthrottled endpoint. Every
// verification path in this file — login, activation and disablement alike —
// shares ONE fixed-window failure counter, keyed on the USER ID, through the
// existing limiter (store.AuthAttemptsOverCap / RecordAuthFailure; see
// store/authratelimit.go for why the account-shaped limit counts only
// failures). No second mechanism was built.
//
// The counter is SHARED across the three endpoints deliberately: an attacker
// must not be able to refresh their guessing budget by switching from
// /login to /2fa/disable.
//
// totpVerifyPerWindow (5 per 5-minute window) is a CONSTANT, not an env var
// and not an instance_settings row — the same choice, for the same reason,
// that store/authratelimit.go makes for the other auth throttles: this is a
// security control, not a product quota, and an operator (or someone who has
// talked their way into the admin console) must not be able to quietly turn it
// down. Being a compile-time constant, it is stricter than those still are.
//
// THE RESIDUAL, STATED HONESTLY. 5 failures per 5 minutes is 1,440 guesses a
// day; at 3-in-10^6 that is roughly a 0.43% chance per day, so an attacker who
// ALREADY HAS THE PASSWORD and guesses flat out around the clock expects to
// succeed in about eight months — while generating 1,440 audited failures a
// day against one account. This is the ordinary posture of throttled TOTP and
// is why the second factor is a second factor and not a replacement for the
// first. A cumulative (NIST SP 800-63B style, ~100 total consecutive failures
// then lock) counter would close it properly; the existing limiter is
// fixed-window by design and building a second mechanism was out of scope.
// Recorded here rather than left for someone to rediscover.
//
// Keying on the user id, not on an attacker-supplied username, keeps this from
// becoming a lockout weapon: the counter is only ever reached AFTER a correct
// password, so a stranger cannot spend a victim's budget at all.
//
// ============================================================================
// ENROL → PROVE → ACTIVATE
// ============================================================================
// POST /v1/auth/2fa/enroll creates a PENDING factor. It gates nothing. Login
// is byte-for-byte unchanged while it exists. Only POST /v1/auth/2fa/activate,
// carrying a code that verifies, turns it on.
//
// The alternative — a secret that gates login the moment it is generated — is
// how you lock a user out of the hub that opens their own gates because a QR
// scan silently failed. See store.CreateTOTPEnrollment.
//
// ============================================================================
// RECOVERY CODES
// ============================================================================
// Ten codes, minted at ACTIVATION (never at enrolment — an abandoned
// enrolment must not leave live credentials behind), shown exactly once, in
// the activation response.
//
// Each is 16 characters of a 32-symbol alphabet = 80 bits of crypto/rand.
// Stored as hex(SHA-256(domain || salt || 0x00 || code)) against a fresh
// 128-bit per-row salt, compared with crypto/subtle.ConstantTimeCompare.
//
// A fast salted digest rather than argon2id, for the reason authrecovery.go
// gives at length: 80 bits of uniform randomness has no dictionary and no
// feasible offline search, so the slow KDF buys nothing — and verification
// must test a presented code against up to ten stored digests, which with
// argon2id would be ten memory-hard derivations per attempt and a denial of
// service handed to anyone who can reach the login endpoint. The salt is
// there to deny precomputation and cross-row correlation from a stolen
// database file.
//
// SINGLE USE, atomically, in the same transaction as the login it authorises
// — store.ClaimSecondFactorAndIssueRefresh. Never "verify then log in" as two
// statements.
//
// ============================================================================
// THE SOLE-ADMIN LOCKOUT QUESTION, ANSWERED RATHER THAN IMPLIED
// ============================================================================
// A sole instance admin who loses their authenticator must not be permanently
// locked out of the hub that opens their gates. Three things answer it, in
// order:
//
//  1. Nobody is forced into 2FA. It is opt-in per user; there is no instance
//     policy that mandates it, so an admin who never enrols is never at risk.
//  2. The ten recovery codes, shown once at activation, are the intended
//     answer, and GET /v1/auth/2fa reports how many remain so the count
//     cannot silently reach zero unnoticed. Any one of them logs the user in
//     AND is sufficient to disable 2FA outright.
//  3. If every code is also lost: this is a SELF-HOSTED hub. The operator has
//     the machine. `UPDATE user_totp SET disabled_at = unixepoch() WHERE
//     user_id = ...` against lintel.db, with the server stopped, restores
//     password-only login. That requires shell access to the box, which is a
//     strictly higher bar than the console login being protected — so it is a
//     legitimate last resort and not a bypass.
//
// Honest gap: (3) is a documented manual procedure, not a `gateway 2fa
// disable --user` subcommand. A supported command would be better than a hand
// -written UPDATE, and adding one to cmd/gateway is the obvious next step.
//
// Separately, and worth stating: losing console access does not lock anyone
// out of a BUILDING. Physical access does not route through this login —
// controllers hold their own keys, offline grants (offline_grants.go) are
// issued in advance precisely for the no-console case, and the chat channels
// authenticate against provider signatures, not against a session.

