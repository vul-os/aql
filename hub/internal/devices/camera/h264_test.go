func TestUnsupportedPacketizationTypeIsReportedNotPanicked(t *testing.T) {
	// Type 26 is MTAP16 — a real RFC 6184 packetization mode, just not one
	// this package implements (see h264.go's doc comment for why).
	payload := []byte{26, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}
	d := NewDepacketizer()
	nals, err := d.Push(buildRTP(1, payload))
	if err == nil {
		t.Fatal("want an error naming the unsupported type, not a silent drop or a panic")
	}
	if len(nals) != 0 {
		t.Fatalf("got %d NALs, want 0", len(nals))
	}
}

func TestTruncatedRTPPacketDoesNotPanic(t *testing.T) {
	d := NewDepacketizer()
	for _, n := range []int{0, 1, 8, 11} {
		if _, err := d.Push(make([]byte, n)); err == nil {
			t.Errorf("a %d-byte packet (shorter than the 12-byte RTP header) was accepted", n)
		}
	}
}

// A malformed RTP header — a CSRC count or an extension length that runs past
// the packet — is exactly as wire-controlled and exactly as unbounded as a
// STAP-A size, and must be checked the same way: before it is used to slice,
// not after.
func TestRTPHeaderBoundsChecks(t *testing.T) {
	t.Run("CSRC count runs past the packet", func(t *testing.T) {
		pkt := make([]byte, 12)
		pkt[0] = 0x8F // version=2, CC=1111=15 (claims 15 CSRC words = 60 bytes)
		if _, _, err := parseRTPHeader(pkt); err == nil {
			t.Fatal("want an error, not a panic, for a CSRC count the packet cannot hold")
		}
	})
	t.Run("extension length runs past the packet", func(t *testing.T) {
		pkt := make([]byte, 16) // 12-byte header + 4-byte extension header, no data
		pkt[0] = 0x90           // version=2, X=1 (extension present), CC=0
		// Extension header: 2 bytes profile id (unused), 2 bytes length in
		// 32-bit WORDS. Claim 0xFFFF words — far more than exists.
		binary.BigEndian.PutUint16(pkt[14:16], 0xFFFF)
		if _, _, err := parseRTPHeader(pkt); err == nil {
			t.Fatal("want an error for an extension length the packet cannot hold")
		}
	})
	t.Run("padding count exceeds the payload", func(t *testing.T) {
		pkt := make([]byte, 13) // 12-byte header + 1 payload/padding byte
		pkt[0] = 0xA0           // version=2, P=1 (padding present), CC=0
		pkt[12] = 200           // claims 200 bytes of padding in a 1-byte payload
		if _, _, err := parseRTPHeader(pkt); err == nil {
			t.Fatal("want an error for a padding count larger than the payload")
		}
	})
	t.Run("wrong RTP version", func(t *testing.T) {
		pkt := make([]byte, 12)
		pkt[0] = 0x40 // version=1
		if _, _, err := parseRTPHeader(pkt); err == nil {
			t.Fatal("want an error for an RTP version this package does not speak")
		}
	})
}

// ── fuzzing: the properties an example-based test would not think to try ────
//
// The unit tests above check the malformed shapes someone thought of. A
// fuzzer, seeded with the same literal vectors, finds the STAP-A size and
// RTP-header-length combinations nobody wrote by hand — which is exactly
// where an unchecked wire-controlled length turns into a slice panic.

func FuzzDepacketizerPush(f *testing.F) {
	f.Add(buildRTP(1, []byte{0x67, 0x42, 0x00, 0x1e}))                                     // single NAL
	f.Add(buildRTP(2, []byte{0x18, 0x00, 0x02, 0x68, 0xCE, 0x00, 0x03, 0x65, 0x88, 0x84})) // STAP-A
	f.Add(buildRTP(10, []byte{0x5C, 0x85, 0xAA, 0xBB}))                                    // FU-A start
	f.Add(buildRTP(11, []byte{0x5C, 0x05, 0xCC, 0xDD}))                                    // FU-A middle
	f.Add(buildRTP(12, []byte{0x5C, 0x45, 0xEE}))                                          // FU-A end
	f.Add(buildRTP(3, []byte{0x18, 0x00, 0x05, 0xAA, 0xBB}))                               // truncated STAP-A
	f.Add([]byte{})
	f.Add(make([]byte, 11))
	f.Add(buildRTP(1, nil))

	f.Fuzz(func(t *testing.T, raw []byte) {
		d := NewDepacketizer()
		nals, err := d.Push(raw)
		if err != nil {
			return // refusing any single packet is always allowed
		}
		for _, nal := range nals {
			// Every emitted NAL must carry the Annex-B start code this
			// package promises, plus at least one header byte — a NAL
			// "unit" with nothing after the start code is not a unit.
			if len(nal) < 5 {
				t.Fatalf("emitted a %d-byte NAL, shorter than start-code+header", len(nal))
			}
			if !bytes.Equal(nal[:4], []byte{0, 0, 0, 1}) {
				t.Fatalf("emitted NAL % x does not begin with the Annex-B start code", nal)
			}
		}
	})
}

// FuzzDepacketizerSequence drives one Depacketizer with three packets in a
// row, which is what it takes to reach the cross-packet state — an FU-A
// reassembly left in progress across calls — that a single-packet fuzz
// target cannot touch.
func FuzzDepacketizerSequence(f *testing.F) {
	f.Add(
		buildRTP(10, []byte{0x5C, 0x85, 0xAA, 0xBB}),
		buildRTP(11, []byte{0x5C, 0x05, 0xCC, 0xDD}),
		buildRTP(12, []byte{0x5C, 0x45, 0xEE}),
	)
	f.Add(
		buildRTP(20, []byte{0x5C, 0x85, 0xAA}),
		buildRTP(22, []byte{0x5C, 0x45, 0xEE}), // gap
		buildRTP(23, []byte{0x67, 0x42}),       // single NAL after the gap
	)
	f.Add([]byte{}, []byte{}, []byte{})

	f.Fuzz(func(t *testing.T, a, b, c []byte) {
		d := NewDepacketizer()
		for _, pkt := range [][]byte{a, b, c} {
			nals, err := d.Push(pkt)
			if err != nil {
				continue
			}
			for _, nal := range nals {
				if len(nal) < 5 || !bytes.Equal(nal[:4], []byte{0, 0, 0, 1}) {
					t.Fatalf("malformed emitted NAL % x", nal)
				}
			}
		}
		// The counters are a running record, never a claim stronger than
		// what was actually seen: neither can be negative, and only NALs
		// this Depacketizer actually produced can be "emitted".
		if d.Emitted() < 0 || d.Dropped() < 0 {
			t.Fatalf("negative counters: emitted=%d dropped=%d", d.Emitted(), d.Dropped())
		}
	})
}
